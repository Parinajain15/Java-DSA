class DataTypes{
    public static void main(String a[]){
        int num= 24;
        short m=4;
        byte b=1;
        long l=88;

        float f=6.9f;
        double d=6.9;

        char c='p';
        boolean t=true;

        System.out.println(num);
        System.out.println(m);
        System.out.println(b);
        System.out.println(l);
        System.out.println(f);
        System.out.println(d);
        System.out.println(c);
        System.out.println(t);
    }
}