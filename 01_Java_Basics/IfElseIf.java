class IfElseIf 
{
public static void main(String args[])
{
    int x=1;
    int y=2;
    int z=3;
    
    if(x>y && x>z)
    {
        System.out.println("x is greatest" + x);
    }
    else if(y>z)
    {
        System.out.println("y is greatest" + y);
    }
    else
    {
        System.out.println("z is greatest" + " " + z);
    }
}
    
}
