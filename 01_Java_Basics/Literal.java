class Literal{
    public static void main(String a[])
    {
        char c ='a';
        c++;
        System.out.println(c);

        int i = 88;
        double d = i;
        System.out.println(d);

        double num=12e10;
        System.out.println(num);

        System.out.println("the values are called literals");
    }

}