class RelationalOperators
{
public static void main(String args[])
{
    int x=2;
    int y=8;
    boolean result = x<y;
    System.out.println(result);

    int a=3;
    int b=9;
    boolean ans= a>b;
    System.out.println(ans);

    int p=2;
    int q=2;
    boolean u= p>=q;
    System.out.println(u);

    int s=3;
    int t=3;
    boolean v= s!=t;
    System.out.println(v);
}

}